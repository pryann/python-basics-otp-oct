print(10 + 10)
# operandus: egy érték vagy változó, amely részt vesz egy műveletben (10, 20)
# operátor: egy szimbólum  vagy  kulcsszó, ameny egy  műveletet hajt végre az operandusok között
# kifejezés:   egy olyan  kódrészlet, amei egy  értéket  ad vissza

summa = 10 + 20
# utasítás: egy oylan kódrészlet, amely egy vagy több műveletet hajt végre, de nem ad vissza értéket
# operandus: 10, 20
# operátor: +
# kifejezés :  10 + 20
# utasítás: summa = 10 + 20

# dinamikus / statikus típusosság
# static:
#   az adat típusa futtatás előtt van meghatározva
#   a típus előre meg van határozva
#   a típus a kód futása során nem változik
#   pl: int age = 12
# dinamikus: az adat típusa  futásidőben van meghatározva
#   pl: age = 12

# explicit / implicit azaz erősen  vagy gyengén típusos
# a forráskódban látható-e a típus
# explicit: int age = 12
# python pl: age = int("12")

# implicit:
# age = 12
